def build_run_name(cfg: dict[str, Any]) -> str:
    """Encode dataset, data_fraction, noise_type, noise_rate and seed (spec 3)."""
    return (
        f"{cfg['dataset']}"
        f"_d{int(round(cfg['data_fraction'] * 100)):03d}"
        f"_{cfg['noise_type']}{int(round(cfg['noise_rate'] * 100)):02d}"
        f"_s{cfg['seed']}"
    )


def make_dirs() -> None:
    """Create every configured output directory."""
    for key in ("lines_dir", "manifests_dir", "checkpoints_dir", "results_dir", "inspect_dir"):
        PATHS[key].mkdir(parents=True, exist_ok=True)


def use_utf8_stdout() -> None:
    """Devanagari output must not die on a cp1252 console."""
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")


def describe_device() -> str:
    """Report CUDA availability and the device name (spec 2)."""
    import torch

    lines = [
        f"torch {torch.__version__}",
        f"torch.version.cuda: {torch.version.cuda}",
        f"torch.cuda.is_available(): {torch.cuda.is_available()}",
    ]
    if torch.cuda.is_available():
        lines.append(f"device count: {torch.cuda.device_count()}")
        lines.append(f"device name: {torch.cuda.get_device_name(0)}")
    else:
        lines.append("device name: <none - no CUDA device visible>")
    return "\n".join(lines)


def require_cuda() -> "object":
    """Abort with a clear message if CPU only (spec 2)."""
    import torch

    if not torch.cuda.is_available():
        raise RuntimeError(
            "No CUDA device visible. This pipeline is specified to train on GPU; "
            "refusing to fall back to CPU. "
            f"torch={torch.__version__}, torch.version.cuda={torch.version.cuda}"
        )
    return torch.device("cuda")


def set_seeds(seed: int) -> None:
    """Seed every source of randomness and force deterministic cuDNN (spec 2)."""
    import random

    import numpy as np

    random.seed(seed)
    np.random.seed(seed)
    try:
        import torch

        torch.manual_seed(seed)
        torch.cuda.manual_seed_all(seed)
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False
    except ImportError:
        pass
